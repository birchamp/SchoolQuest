/**
 * A whole term, exactly as the app ingested it from the five fake syllabuses.
 *
 * This is not hand-written. It is the `semester-test@example.edu` account dumped straight out of
 * the running Worker after the full journey the UI performs — onboarding, courses, commitments,
 * five syllabus extractions through the model, the clarification answers, and confirmation. Five
 * courses, sixty-one work items, due dates running from August to mid-December.
 *
 * It exists because `buildSeedSemester` is a *small* fixture — two courses, and its work runs
 * out around week fourteen — which is right for testing a single moment and wrong for testing a
 * term. A semester walk driven by it reported the planner "failing" to schedule anything in the
 * last two weeks, when in truth the fixture had simply run dry. A test that cannot tell those
 * two apart is worse than no test.
 *
 * Regenerate it by dumping the seeded account's current plan; the shape here is the plan
 * payload's own, minus the derived views. Grading categories are absent because no route
 * exposes them, so anything reading this runs with no grade data — which is the honest state of
 * a term where nothing has been handed back yet, and the state the health engine is written to
 * survive.
 */
