/**
 * The fixture is pinned to a fixed week so tests stay deterministic. A demo account
 * pinned to that same week would be useless outside it, so every date is shifted by whole
 * weeks to land on the current one. Shifting by a multiple of 7 days preserves the
 * weekday pattern the scenario depends on — the Tuesday library window stays on Tuesday.
 */
const SEED_ANCHOR = "2026-09-07"; // The fixture's Monday.
const DAY_MS = 24 * 60 * 60 * 1000;

function mondayOfThisWeek(): Date {
  const today = new Date();
  const utcMidnight = Date.UTC(today.getUTCFullYear(), today.getUTCMonth(), today.getUTCDate());
  const dayOfWeek = new Date(utcMidnight).getUTCDay();
  // getUTCDay is 0 for Sunday; step back to Monday.
  const offsetToMonday = (dayOfWeek + 6) % 7;
  return new Date(utcMidnight - offsetToMonday * DAY_MS);
}

const shiftWeeks = Math.round(
  (mondayOfThisWeek().getTime() - Date.parse(`${SEED_ANCHOR}T00:00:00Z`)) / (7 * DAY_MS),
);
const shiftMs = shiftWeeks * 7 * DAY_MS;

/** Shifts an ISO date or datetime by whole weeks, preserving the time component. */
function shift<T extends string | null>(value: T): T {
  if (value === null) return value;
  const shifted = new Date(Date.parse(value) + shiftMs).toISOString();
  return (value.length === 10 ? shifted.slice(0, 10) : shifted) as T;
}

/**
 * A DELETE that reaches the seed user's rows in a given table, walking whatever chain of
 * foreign keys connects it back to `users`.
 */
function deleteForSeed(table: string): string {
  const viaCourse = new Set([
    "grading_categories",
    "meeting_patterns",
    "source_documents",
    "work_items",
  ]);
  const viaTerm = new Set(["courses", "availability_rules", "commitments", "plan_versions"]);
  const viaWorkItem = new Set(["grade_results", "work_sessions", "dependencies"]);

  const termScope = `SELECT id FROM terms WHERE user_id = '${SEED_USER_ID}'`;
  const courseScope = `SELECT id FROM courses WHERE term_id IN (${termScope})`;
  const workItemScope = `SELECT id FROM work_items WHERE course_id IN (${courseScope})`;

  if (viaTerm.has(table)) return `DELETE FROM ${table} WHERE term_id IN (${termScope});`;
  if (viaCourse.has(table)) return `DELETE FROM ${table} WHERE course_id IN (${courseScope});`;
  if (viaWorkItem.has(table)) {
    const column =
      table === "dependencies" ? "successor_work_item_id" : "work_item_id";
    return `DELETE FROM ${table} WHERE ${column} IN (${workItemScope});`;
  }
  return `DELETE FROM ${table} WHERE user_id = '${SEED_USER_ID}';`;
}

